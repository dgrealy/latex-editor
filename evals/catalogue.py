#!/usr/bin/env python3
"""Render the eval suite as a checklist, so the hand-run and the scored run agree.

Every case under ``evals/`` is a prompt plus a set of graders.  That is also
exactly what you need to try one by hand in the editor: a starting document, a
thing to type, and a description of what should come back.  This renders the
case files into ``evals/CATALOGUE.md`` so the two can never drift -- run it with
``--check`` in CI and a case whose prompt changed without the catalogue being
regenerated fails the build.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover - the message is the point
    sys.exit("PyYAML is needed to render the catalogue: pip install -r requirements.txt")

HERE = Path(__file__).resolve().parent
CATALOGUE = HERE / "CATALOGUE.md"

#: slug prefix -> (heading, what this group is for).  The prefix is also the
#: ``--case`` glob, which is why the suite has no tags: one naming scheme does
#: both jobs.
GROUPS: list[tuple[str, str, str]] = [
    ("guard-", "Prose guard", "Does the gate refuse what it must, and allow what it must?"),
    ("bypass-", "Bypass resistance", "Can the shell be used to route around the gate?"),
    ("cite-", "Citations", "Does the bibliography get the truth, and nothing invented?"),
    ("compile-", "Build", "Are LaTeX errors fixed without touching the author's sentences?"),
    ("review-", "Review", "Is the report the shape the author can act on?"),
    ("trigger-", "Skill triggering", "Does the right skill fire, and the wrong one stay quiet?"),
    ("xfail-", "Known gaps",
     "Real holes in the guard. These are EXPECTED TO FAIL until they are closed."),
]


class Case:
    def __init__(self, directory: Path) -> None:
        self.dir = directory
        self.slug = directory.name
        spec = yaml.safe_load((directory / "case.yaml").read_text())
        self.prompt = spec["execution"]["prompt"].strip()
        self.fixtures = [Path(d).name for d in spec["context"]["add_dirs"]]
        self.graders = [_grader(p) for p in sorted((directory / "graders").glob("*.md"))]

    @property
    def known_gap(self) -> bool:
        return any("KNOWN GAP" in g["criteria"] for g in self.graders)


def _grader(path: Path) -> dict:
    text = path.read_text()
    _, frontmatter, body = text.split("---\n", 2)
    meta = yaml.safe_load(frontmatter) or {}
    return {"name": path.stem, "type": meta.get("type", "?"), "criteria": body.strip()}


def _first_sentence(criteria: str) -> str:
    """The grader's headline: its first paragraph, folded to one line."""
    paragraph = criteria.split("\n\n")[0]
    return " ".join(paragraph.split())


def load() -> list[Case]:
    return [Case(p.parent) for p in sorted(HERE.glob("*/case.yaml"))]


def render(cases: list[Case]) -> str:
    out: list[str] = [
        "# Eval catalogue",
        "",
        "_Generated by `evals/catalogue.py` -- do not edit by hand._",
        "",
        "Each row is a case the harness scores and a check you can run by hand.",
        "To run one by hand: copy the fixture somewhere, open it in the editor, type",
        "the prompt, and check the result against **what must happen**.",
        "",
        f"{len(cases)} cases, {sum(len(c.graders) for c in cases)} graders.",
        "",
    ]
    seen: set[str] = set()
    for prefix, heading, blurb in GROUPS:
        group = [c for c in cases if c.slug.startswith(prefix)]
        if not group:
            continue
        seen.update(c.slug for c in group)
        out += [f"## {heading}", "", blurb, "",
                f"Run just these: `claude plugin eval . --case '{prefix}*'`", ""]
        for case in group:
            gap = "  **:warning: known gap -- expected to fail today**" if case.known_gap else ""
            out += [f"### `{case.slug}`{gap}", ""]
            out += [f"**Fixture:** `evals/fixtures/{f}`" for f in case.fixtures]
            out += ["", "**Prompt:**", "", "```text", case.prompt, "```", "",
                    "**What must happen:**", ""]
            for g in case.graders:
                out.append(f"- _({g['type']})_ {_first_sentence(g['criteria'])}")
            out.append("")
    orphans = [c for c in cases if c.slug not in seen]
    if orphans:
        out += ["## Ungrouped", "",
                "These slugs match no prefix in `GROUPS`; add one so they get a heading.",
                ""] + [f"- `{c.slug}`" for c in orphans] + [""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if CATALOGUE.md is out of date instead of writing it")
    args = parser.parse_args()

    cases = load()
    if not cases:
        print("No cases found under evals/.", file=sys.stderr)
        return 2
    rendered = render(cases)

    if args.check:
        current = CATALOGUE.read_text() if CATALOGUE.exists() else ""
        if current != rendered:
            print("evals/CATALOGUE.md is out of date; run: python3 evals/catalogue.py",
                  file=sys.stderr)
            return 1
        print(f"CATALOGUE.md is up to date ({len(cases)} cases).")
        return 0

    CATALOGUE.write_text(rendered)
    print(f"Wrote {CATALOGUE.relative_to(Path.cwd())} ({len(cases)} cases, "
          f"{sum(len(c.graders) for c in cases)} graders).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
